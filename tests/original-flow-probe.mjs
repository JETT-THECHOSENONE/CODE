import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root=process.cwd();
const isMobile=process.argv.includes('--mobile');
const viewport=isMobile?{width:390,height:844}:{width:1440,height:900};
const out=path.join(root,'docs','reference','original-flow',isMobile?'mobile-390':'desktop-1440');
await mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true});
const a=await browser.newContext({viewport,locale:'zh-CN'});
const page=await a.newPage();
const diagnostics=[];
page.on('console',msg=>diagnostics.push({type:'console',level:msg.type(),text:msg.text()}));
page.on('requestfailed',req=>diagnostics.push({type:'requestfailed',url:req.url(),error:req.failure()?.errorText}));
await page.goto('https://www.sameword.top/?lang=zh',{waitUntil:'domcontentloaded',timeout:30000});
await page.locator('input').first().fill('视觉测试甲');
await page.getByRole('button',{name:/创建我的房间/}).click();
await page.waitForTimeout(12000);
await page.screenshot({path:path.join(out,'01-after-create.png'),fullPage:true});
const created={url:page.url(),text:await page.locator('body').innerText(),buttons:await page.getByRole('button').allTextContents(),inputs:await page.locator('input').count(),diagnostics};
await writeFile(path.join(out,'01-after-create.json'),JSON.stringify(created,null,2),'utf8');

const b=await browser.newContext({viewport,locale:'zh-CN'});
const guest=await b.newPage();
await guest.goto(page.url(),{waitUntil:'domcontentloaded',timeout:30000});
await guest.waitForTimeout(6000);
await guest.screenshot({path:path.join(out,'02-guest-entry.png'),fullPage:true});
const guestEntry={url:guest.url(),text:await guest.locator('body').innerText(),buttons:await guest.getByRole('button').allTextContents(),inputs:await guest.locator('input').count()};
await writeFile(path.join(out,'02-guest-entry.json'),JSON.stringify(guestEntry,null,2),'utf8');
const roomCode=new URL(page.url()).searchParams.get('r')||'';
const guestInputs=guest.locator('input');
if(await guestInputs.count()>=2){await guestInputs.nth(0).fill(roomCode);await guestInputs.nth(1).fill('视觉测试乙');}
const joinButton=guest.getByRole('button',{name:'加入房间',exact:true}).last();
if(await joinButton.count())await joinButton.click();
await guest.waitForTimeout(6000);
await guest.screenshot({path:path.join(out,'03-guest-joined.png'),fullPage:true});
await page.waitForTimeout(2500);
await page.screenshot({path:path.join(out,'04-full-lobby.png'),fullPage:true});
const fullLobby={hostText:await page.locator('body').innerText(),hostButtons:await page.getByRole('button').allTextContents(),guestText:await guest.locator('body').innerText()};
await writeFile(path.join(out,'04-full-lobby.json'),JSON.stringify(fullLobby,null,2),'utf8');
const start=page.getByRole('button',{name:/开始第 1 轮/});
if(await start.count())await start.click({timeout:12000});
await page.waitForTimeout(3000);
await page.screenshot({path:path.join(out,'05-round-input.png'),fullPage:true});
const round={hostText:await page.locator('body').innerText(),hostButtons:await page.getByRole('button').allTextContents(),hostInputs:await page.locator('input').count(),guestText:await guest.locator('body').innerText()};
await writeFile(path.join(out,'05-round-input.json'),JSON.stringify(round,null,2),'utf8');
if(await page.locator('input').count())await page.locator('input').first().fill('苹果');
if(await guest.locator('input').count())await guest.locator('input').first().fill('苹果');
const hostSubmit=page.getByRole('button',{name:/锁定答案/});
const guestSubmit=guest.getByRole('button',{name:/锁定答案/});
if(await hostSubmit.count())await hostSubmit.click();
if(await guestSubmit.count())await guestSubmit.click();
await page.waitForTimeout(900);
await page.screenshot({path:path.join(out,'06-after-submit.png'),fullPage:true});
const afterSubmit={hostText:await page.locator('body').innerText(),hostButtons:await page.getByRole('button').allTextContents()};
await writeFile(path.join(out,'06-after-submit.json'),JSON.stringify(afterSubmit,null,2),'utf8');
await page.waitForTimeout(4500);
await page.screenshot({path:path.join(out,'07-later-state.png'),fullPage:true});
const later={hostText:await page.locator('body').innerText(),hostButtons:await page.getByRole('button').allTextContents()};
await writeFile(path.join(out,'07-later-state.json'),JSON.stringify(later,null,2),'utf8');
console.log(JSON.stringify({created,guestEntry,fullLobby,round,afterSubmit,later},null,2));
await browser.close();
